const languageOptions = {
    en: { label: "English" },
    sv: { label: "Svenska" },
    de: { label: "Deutsch" },
};

function normalizeText(text) {
    return text.replace(/\s+/g, " ").trim();
}

function translateStaticText(text, language) {
    if (language === "en") {
        return text;
    }

    return siteTranslations[language]?.[normalizeText(text)] || text;
}

function translateNodeText(node, language) {
    if (!node.nodeValue.trim()) {
        return;
    }

    if (!node.__originalText) {
        node.__originalText = node.nodeValue;
    }

    const original = node.__originalText;
    const leading = original.match(/^\s*/)?.[0] || "";
    const trailing = original.match(/\s*$/)?.[0] || "";
    const translated = translateStaticText(original, language);

    node.nodeValue = `${leading}${translated}${trailing}`;
}

function translateAttributes(language) {
    const attributeMap = [
        ["[data-guests-price]", "aria-label", "Guests for price estimate", { sv: "Gäster för prisberäkning", de: "Gäste für Preisberechnung" }],
        ["textarea[name='message']", "placeholder", "Who is travelling, what brings you to Dalarna, and anything helpful for us to know.", {
            sv: "Vilka reser, vad tar er till Dalarna och finns det något annat som är bra för oss att veta?",
            de: "Wer reist, was führt Sie nach Dalarna und gibt es noch etwas, das wir wissen sollten?"
        }],
        ["input[name='guest_name']", "placeholder", "Name", { sv: "Namn", de: "Name" }],
        ["input[name='guest_email']", "placeholder", "you@example.com", { sv: "du@example.com", de: "sie@example.com" }],
        ["input[name='guest_phone']", "placeholder", "+46 ...", { sv: "+46 ...", de: "+49 ..." }],
        ["[data-prev-month]", "aria-label", "Previous month", { sv: "Föregående månad", de: "Vorheriger Monat" }],
        ["[data-next-month]", "aria-label", "Next month", { sv: "Nästa månad", de: "Nächster Monat" }]
    ];

    attributeMap.forEach(([selector, attribute, english, translations]) => {
        document.querySelectorAll(selector).forEach((element) => {
            element.setAttribute(attribute, language === "en" ? english : translations[language] || english);
        });
    });
}

function languageFromUrl() {
    const language = new URLSearchParams(window.location.search).get("lang");
    return Object.prototype.hasOwnProperty.call(languageOptions, language) ? language : "";
}

function localizeInternalLanguageLinks(language) {
    document.querySelectorAll("a[href]").forEach((link) => {
        const href = link.getAttribute("href");
        if (!href || href.startsWith("#") || href.startsWith("mailto:") || href.startsWith("tel:")) {
            return;
        }

        const isBookingLink = href === "booking.html" || href.startsWith("booking.html#") || href.startsWith("booking.html?");
        const isHomeLink = href === "index.html" || href.startsWith("index.html#") || href.startsWith("index.html?");
        const isHouseLink = href === "house.html" || href.startsWith("house.html#") || href.startsWith("house.html?");
        if (!isBookingLink && !isHomeLink && !isHouseLink) {
            return;
        }

        const [pathWithQuery, hash = ""] = href.split("#");
        const [path] = pathWithQuery.split("?");
        link.setAttribute("href", `${path}?lang=${language}${hash ? `#${hash}` : ""}`);
    });
}

function applyLanguage(language) {
    document.documentElement.lang = language;
    document.querySelectorAll("[data-language-switcher] button").forEach((button) => {
        const active = button.dataset.language === language;
        button.classList.toggle("active", active);
        button.setAttribute("aria-pressed", String(active));
    });

    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
        acceptNode(node) {
            if (node.parentElement?.closest("[data-no-translate]")) {
                return NodeFilter.FILTER_REJECT;
            }
            if (["SCRIPT", "STYLE"].includes(node.parentElement?.tagName)) {
                return NodeFilter.FILTER_REJECT;
            }
            return NodeFilter.FILTER_ACCEPT;
        }
    });

    const nodes = [];
    while (walker.nextNode()) {
        nodes.push(walker.currentNode);
    }
    nodes.forEach((node) => translateNodeText(node, language));
    translateAttributes(language);
    localizeInternalLanguageLinks(language);
    localStorage.setItem("lakeHouseLanguage", language);
    window.dispatchEvent(new CustomEvent("site-language-change", { detail: { language } }));
}

function createLanguageSwitcher() {
    document.querySelectorAll(".navbar").forEach((navbar) => {
        if (navbar.querySelector("[data-language-switcher]")) {
            return;
        }

        const switcher = document.createElement("div");
        switcher.className = "language-switcher";
        switcher.setAttribute("data-language-switcher", "");
        switcher.setAttribute("aria-label", "Language");
        switcher.innerHTML = Object.entries(languageOptions).map(([code, option]) => (
            `<button type="button" data-language="${code}" aria-label="${option.label}" title="${option.label}"><span class="flag flag-${code}" aria-hidden="true"></span><small>${code.toUpperCase()}</small></button>`
        )).join("");

        navbar.appendChild(switcher);
    });
}

function getCurrentLanguage() {
    const language = languageFromUrl() || localStorage.getItem("lakeHouseLanguage") || "en";
    return Object.prototype.hasOwnProperty.call(languageOptions, language) ? language : "en";
}

function t(english, replacements = {}) {
    let translated = translateStaticText(english, getCurrentLanguage());
    Object.entries(replacements).forEach(([key, value]) => {
        translated = translated.replaceAll(`{${key}}`, value);
    });
    return translated;
}

document.addEventListener("DOMContentLoaded", () => {
    createLanguageSwitcher();
    document.addEventListener("click", (event) => {
        const button = event.target.closest("[data-language-switcher] button");
        if (button) {
            applyLanguage(button.dataset.language);
        }
    });
    applyLanguage(getCurrentLanguage());
});

window.siteI18n = {
    getCurrentLanguage,
    applyLanguage,
    t,
    translateStaticText,
};
